/// A closed set of presentation messages supported by the Spanish and English
/// catalogs. Domain values, API values, and persistence values do not belong
/// here: this enum is only for text shown by the application shell and other
/// presentation surfaces.
macro_rules! define_message_keys {
    ($($variant:ident => $name:literal),+ $(,)?) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        pub enum MessageKey {
            $($variant),+
        }

        impl MessageKey {
            /// Generated from the same declaration as the enum so a variant
            /// cannot be omitted from the complete catalog-parity key set.
            pub const ALL: &'static [Self] = &[$(Self::$variant),+];

            pub const fn as_str(self) -> &'static str {
                match self {
                    $(Self::$variant => $name),+
                }
            }
        }
    };
}

